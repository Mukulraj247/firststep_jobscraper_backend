export function normalizeCityKey(raw: string): string {
  let s = String(raw || '')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\./g, ' ')
    .replace(/'/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9+ ]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  s = s.replace(/^(city of|town of|village of)\s+/i, '');
  s = s.replace(/\s+(city|town|village|borough|cdp)$/i, '');
  // St / Saint
  s = s.replace(/\bst\b/g, 'st');
  s = s.replace(/\bsaint\b/g, 'st');
  if (CITY_ALIASES[s]) s = CITY_ALIASES[s];
  return s;
}

function cityKeyFromName(name: string): string {
  return normalizeCityKey(name);
}

const BY_KEY = new Map<string, CityCandidate[]>();

for (const [name, state, population] of CITY_ROWS) {
  const key = cityKeyFromName(name);
  const list = BY_KEY.get(key) || [];
  // Dedupe same state
  if (!list.some((c) => c.state === state)) {
    list.push({ name, state, population });
  } else {
    const existing = list.find((c) => c.state === state)!;
    if (population > existing.population) existing.population = population;
  }
  BY_KEY.set(key, list);
}

export function lookupCityCandidates(cityRaw: string): CityCandidate[] {
  const key = normalizeCityKey(cityRaw);
  if (!key) return [];
  const direct = BY_KEY.get(key);
  if (direct?.length) return [...direct].sort((a, b) => b.population - a.population);

  // Alias may point at another key
  const aliased = CITY_ALIASES[key];
  if (aliased && aliased !== key) {
    const via = BY_KEY.get(aliased);
    if (via?.length) return [...via].sort((a, b) => b.population - a.population);
  }
  return [];
}

export function lookupZipState(zipRaw: string): string | null {
  const zip = String(zipRaw || '').replace(/\D/g, '').slice(0, 5);
  if (zip.length !== 5) return null;
  if (ZIP_TO_STATE[zip]) return ZIP_TO_STATE[zip];
  const z3 = zip.slice(0, 3);
  return ZIP3_TO_STATE[z3] || null;
}

export function gazetteerStats(): { cities: number; keys: number; zips: number } {
  let cities = 0;
  for (const list of BY_KEY.values()) cities += list.length;
  return {
    cities,
    keys: BY_KEY.size,
    zips: Object.keys(ZIP_TO_STATE).length,
  };
}
